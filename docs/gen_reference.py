"""Generate docs/reference-config.md from profilekit/schema.json.

Run after every schema change:  python3 docs/gen_reference.py
Check in CI or before a commit:  python3 docs/gen_reference.py --check   (exit 1 when the file is stale)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = json.loads((ROOT / "profilekit" / "schema.json").read_text(encoding="utf-8"))
OUT = ROOT / "docs" / "reference-config.md"

TABLE_ORDER = ["profile", "hub", "links", "status", "focus", "org", "terminal", "recommend", "contributions",
               "city", "lightup", "sections"]


def typ(s):
    if "enum" in s:
        return "one of " + ", ".join(f"`{v}`" if not isinstance(v, str) else f'`"{v}"`' for v in s["enum"])
    t = s.get("type", "")
    if t == "array":
        inner = s.get("items", {})
        if "enum" in inner:
            return "list of " + ", ".join(f'`"{v}"`' for v in inner["enum"])
        if inner.get("type") == "object":
            return "list of tables"
        return f"list of {inner.get('type', 'values')}s"
    return {"object": "table", "string": "string", "number": "number", "boolean": "boolean"}.get(t, t)


def limits(s):
    out = []
    if "maxLength" in s:
        out.append(f"max {s['maxLength']} chars")
    if "pattern" in s:
        out.append(f"pattern `{s['pattern']}`")
    if "minimum" in s:
        out.append(f"{s['minimum']} to {s['maximum']}")
    if "maxItems" in s:
        out.append(f"max {s['maxItems']} items")
    if "minItems" in s:
        out.append(f"min {s['minItems']} item")
    if s.get("uniqueItems"):
        out.append("no duplicates")
    inner = s.get("items", {})
    if inner.get("type") == "string" and "maxLength" in inner:
        out.append(f"each max {inner['maxLength']} chars")
    if inner.get("type") == "string" and "pattern" in inner:
        out.append(f"each matches `{inner['pattern']}`")
    return "; ".join(out)


def rows(props, required, prefix=""):
    lines = []
    for key, s in props.items():
        req = "yes" if key in required else ""
        default = f"`{json.dumps(s['default'], ensure_ascii=False)}`" if "default" in s else ""
        desc = s.get("description", "")
        lines.append(f"| `{prefix}{key}` | {typ(s)} | {req} | {default} | {limits(s)} | {desc} |")
    return lines


def render():
    props = SCHEMA["properties"]
    out = ["# Reference: profile.toml", "",
           "<!-- Generated by docs/gen_reference.py from profilekit/schema.json. Do not edit by hand. -->", "",
           SCHEMA["description"], "",
           "Length limits are layout limits: a longer text would not fit its graphic. "
           "Validate any file with `python3 -m profilekit validate`; see the [CLI reference](reference-cli.md). "
           "For worked examples, read [how to design your skyline](howto-design-your-skyline.md) and "
           "[`profilekit/example.toml`](../profilekit/example.toml).", "",
           "Contents: " + " · ".join(f"[`{k}`](#{k})" for k in TABLE_ORDER), ""]
    for key in TABLE_ORDER:
        s = props[key]
        array = s.get("type") == "array" and s.get("items", {}).get("type") == "object"
        header = f"[[{key}]]" if array else ("top level" if key == "sections" else f"[{key}]")
        out += [f"## {key}", "", f"TOML: `{header}`" + (" (repeat the table for each entry)" if array else ""), ""]
        if s.get("description"):
            out += [s["description"], ""]
        if key == "sections":
            out += ["| Type | Default | Limits |", "|---|---|---|",
                    f"| {typ(s)} | `{json.dumps(['header', 'contact', 'focus', 'org', 'terminal', 'recommend', 'contributions', 'city', 'lightup'])}` | {limits(s)} |", ""]
            continue
        target = s["items"] if array else s
        if array:
            lim = limits(s)
            if lim:
                out += [f"List limits: {lim}.", ""]
        out += ["| Key | Type | Required | Default | Limits | Description |", "|---|---|---|---|---|---|"]
        out += rows(target.get("properties", {}), target.get("required", []))
        out.append("")
        for sub, ss in target.get("properties", {}).items():
            nested = ss.get("items", {}) if ss.get("type") == "array" else ss
            if nested.get("type") == "object" and nested.get("properties"):
                kind = f"[[{key}.{sub}]]" if ss.get("type") == "array" else f"{key}.{sub} = {{ ... }}"
                out += [f"### {key}.{sub}", "", f"TOML: `{kind}`", ""]
                if ss.get("description"):
                    out += [ss["description"], ""]
                out += ["| Key | Type | Required | Default | Limits | Description |", "|---|---|---|---|---|---|"]
                out += rows(nested["properties"], nested.get("required", []))
                out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/reference-config.md is stale; run python3 docs/gen_reference.py")
            sys.exit(1)
        print("docs/reference-config.md is up to date")
        sys.exit(0)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
